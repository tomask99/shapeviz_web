export function translate(text, locale = 'en') {
  if (locale !== 'sk' || typeof text !== 'string') return text;
  if (Object.hasOwn(sk, text)) return sk[text];
  if (text.startsWith('Enlarge: ')) return 'Zväčšiť: ' + translate(text.slice(9), locale);
  return text;
}
